function discoveryProductType(category:string) {
  switch(category.normalize('NFKC').trim().toLowerCase()) {
    case 'gift card': case 'gift cards': case 'giftcard': return 'Gift cards';
    case 'mobile & telecom': case 'mobile recharge': case 'mobile top-up': case 'mobile top up': return 'Mobile recharge';
    default: return category;
  }
}
/** Read-only administration. Authoritative prices are generated by the existing
 * exact arithmetic code. No write, approval or publication port is available. */
export class StaffCatalogueService {
  readonly #cursors=new Map<string,{binding:string;revision:string;anchor:string;direction:'next'|'previous';expires:number}>();
  constructor(private readonly deps:{authority:AdministrationAuthority;read(ticket:StaffCatalogueReadTicket):Promise<StaffCatalogueSnapshot>;
    audit(lease:AdministrationLease,view:StaffCatalogueView):Promise<void>;now:()=>Date;
    configuredDiscoveryProviders?:readonly string[]}){}
  async available(identity:VerifiedStaffIdentity,tenantId:string):Promise<boolean> {
    const lease=await this.deps.authority.require(identity,tenantId,'catalog.read');
    return lease.revalidate();
  }
  async read(identity:VerifiedStaffIdentity,tenantId:string,view:StaffCatalogueView,query:Readonly<Record<string,unknown>>){
    const supported:Readonly<Record<StaffCatalogueView,readonly string[]>>={countries:['country','group'],services:['country','group','service','provider'],providers:['country','group','service','provider'],products:['country','group','service','provider','product','search'],offers:['country','group','service','provider','product','search'],economics:['country','group','service','provider','product','search'],imports:['provider'],drafts:['product'],publications:['product'],discoveries:['provider','search','sourceCountry','sourceRegion','productType','discoveryId'],'discovery-providers':[]};
    if(!Object.hasOwn(supported,view))throw new AdministrationError(400);
    if(Object.keys(query).some(k=>!['sort','limit','cursor',...supported[view]].includes(k)))throw new AdministrationError(400);
    const q:Record<string,string>={};for(const [key,value] of Object.entries(query)){if(!text(value)||!value.trim())throw new AdministrationError(400);q[key]=value;}
    if(q['country']&&!CATALOGUE_COUNTRIES.some(c=>c.code===q['country'])||q['sourceCountry']&&!/^[A-Z]{3}$/.test(q['sourceCountry'])||
      q['sourceRegion']&&!sourceRegions.has(q['sourceRegion'])||q['group']&&!['GCC','OTHER_ASIA','AFRICA','EUROPE'].includes(q['group'])||
      q['service']&&!/^[A-Z][A-Z0-9_]{1,31}$/.test(q['service'])||q['provider']&&!/^[A-Za-z0-9_.:-]{1,128}$/.test(q['provider'])||
      q['product']&&!administrationUuid.test(q['product'])||q['discoveryId']&&!administrationUuid.test(q['discoveryId'])||
      q['sort']&&!['id','name'].includes(q['sort'])||q['cursor']&&!/^[0-9a-f]{64}$/.test(q['cursor']))throw new AdministrationError(400);
    const limit=q['limit']===undefined?20:/^[1-9][0-9]?$/.test(q['limit'])?Number(q['limit']):0;if(limit<1||limit>50)throw new AdministrationError(400);
    const lease=await this.deps.authority.require(identity,tenantId,'catalog.read');
    const pricing = ['economics','offers','drafts','publications'].includes(view)
      ? await this.deps.authority.require(identity, tenantId, 'pricing.read')
      : null;
    if (pricing && (pricing.staffId !== lease.staffId || pricing.tenantId !== lease.tenantId)) {
      throw new AdministrationError(403);
    }
    const revalidate = async () => await lease.revalidate() && (!pricing || await pricing.revalidate());
    if (!await revalidate()) throw new AdministrationError(403);
    const ticket=Object.freeze({tenantId,view,revalidate});tickets.add(ticket);
    let snapshot:StaffCatalogueSnapshot;try{snapshot=await this.deps.read(ticket);}finally{tickets.delete(ticket);}
    if(snapshot.tenantId!==tenantId||!text(snapshot.revision)||[snapshot.availability,snapshot.products,snapshot.offers,snapshot.proposals,snapshot.imports,snapshot.drafts,snapshot.publications??[],snapshot.storedEconomics??[],snapshot.discoveries??[],snapshot.discoveryProviderIds??[],snapshot.hybridPricingEvidence??[]].some(rows=>!Array.isArray(rows)||rows.length>1000))throw new AdministrationError(503);
    const seen=new Set<string>();
    for(const a of snapshot.availability){const key=JSON.stringify([a.country,a.service,a.providerId]);if(!CATALOGUE_COUNTRIES.some(c=>c.code===a.country)||!text(a.service)||!text(a.providerId)||typeof a.enabled!=='boolean'||seen.has(key))throw new AdministrationError(503);seen.add(key);}
    const country=(code:string)=>CATALOGUE_COUNTRIES.find(c=>c.code===code);
    const matches=(c:string,s:string,p?:string)=> (!q['country']||c===q['country'])&&(!q['group']||country(c)?.group===q['group'])&&(!q['service']||s===q['service'])&&(!q['provider']||p===q['provider']);
    const configured=(c:string,s:string,p:string)=>snapshot.availability.some(a=>a.enabled&&a.country===c&&a.service===s&&a.providerId===p);
    const products=snapshot.products.map(p=>{if(!administrationUuid.test(p.id)||!text(p.name)||!country(p.country)||!text(p.service))throw new AdministrationError(503);return Object.freeze({id:p.id,name:p.name,country:p.country,service:p.service});});
    if(new Set(products.map(p=>p.id)).size!==products.length)throw new AdministrationError(503);
    const now=this.deps.now().getTime();if(!Number.isSafeInteger(now))throw new AdministrationError(503);
    const offers=snapshot.offers.map(o=>{
      const product=products.find(p=>p.id===o.productId);if(!product||!administrationUuid.test(o.id)||!text(o.providerId)||typeof o.available!=='boolean'||!Number.isFinite(Date.parse(o.validUntil)))throw new AdministrationError(503);
      const observed=o.sourceObservedAt,completed=o.sourceCompletedAt;
      if((observed!==undefined||completed!==undefined)&&(
        typeof observed!=='string'||typeof completed!=='string'||!Number.isFinite(Date.parse(observed))||
        !Number.isFinite(Date.parse(completed))||Date.parse(completed)<Date.parse(observed)))throw new AdministrationError(503);
      let cost: string | undefined;
      if(view==='offers'){
        if(typeof o.providerCostMinor!=='bigint')throw new AdministrationError(503);
        assertMinorAmount(o.providerCostMinor,'provider cost');
        cost=formatAed(o.providerCostMinor);
      }
      return Object.freeze({id:o.id,productId:o.productId,providerId:o.providerId,country:product.country,service:product.service,available:o.available&&configured(product.country,product.service,o.providerId)&&Date.parse(o.validUntil)>now,
        freshness:Date.parse(o.validUntil)>now?'CURRENT':'EXPIRED',validUntil:o.validUntil,
        ...(view==='offers'&&observed!==undefined&&{sourceObservedAt:observed,sourceCompletedAt:completed}),
        ...(cost!==undefined&&{providerCost:cost})});
    });
    let rows:readonly Readonly<{id:string;name?:string;[key:string]:unknown}>[];
    if(view==='countries')rows=CATALOGUE_COUNTRIES.filter(c=>(!q['group']||c.group===q['group'])&&(!q['country']||c.code===q['country'])).map(c=>Object.freeze({id:c.code,...c,configured:snapshot.availability.some(a=>a.enabled&&a.country===c.code)}));
    else if(view==='services'||view==='providers')rows=[...new Map(snapshot.availability.filter(a=>a.enabled&&matches(a.country,a.service,a.providerId)).map(a=>{const id=view==='services'?a.service:a.providerId;return [id,Object.freeze({id,name:id})] as const;})).values()];
    else if(view==='products')rows=products.filter(p=>matches(p.country,p.service,q['provider'])&&(!q['provider']||offers.some(o=>o.productId===p.id&&o.providerId===q['provider']))&&(!q['product']||p.id===q['product'])).map(p=>Object.freeze({...p,available:offers.some(o=>o.productId===p.id&&o.available&&(!q['provider']||o.providerId===q['provider']))}));
    else if(view==='offers')rows=offers.filter(o=>matches(o.country,o.service,o.providerId)&&(!q['product']||o.productId===q['product']));
    else if(view==='economics') {
      const calculated = snapshot.proposals
        .filter(r => !q['product'] || r.productId === q['product'])
        .flatMap(r => {
          if (r.tenantId !== tenantId) throw new AdministrationError(503);
          const draft=generateDraftPublicationCandidate(r);
          if (draft.selectedProviderId!=='FINXPLOR') return [draft];
          const evidence=snapshot.hybridPricingEvidence?.find(row=>row.job.request.offerId===draft.selectedOfferId&&
            row.job.request.snapshotId===draft.selectedSnapshotId&&row.job.request.candidateProductId===r.productId);
          if(!evidence)return [];
          try{return [reviewHybridPricing(r,evidence,new Date(now)).draft];}
          catch{throw new AdministrationError(503);}
        });
      rows = [...calculated, ...(snapshot.storedEconomics ?? [])].flatMap(candidate => {
        if (q['product'] && candidate.productId !== q['product']) return [];
        const product = products.find(p => p.id === candidate.productId);
        if (!product || !/^[a-f0-9]{64}$/.test(candidate.candidateId)) throw new AdministrationError(503);
        if (!matches(product.country, product.service, candidate.selectedProviderId)) return [];
        return [Object.freeze({
          id: product.id, candidateId: candidate.candidateId, name: product.name,
          total: formatAed(candidate.totalAmountMinor), providerCost: formatAed(candidate.providerCostMinor),
          serviceFee: formatAed(candidate.serviceFeeMinor), paymentFee: formatAed(candidate.paymentFeeMinor),
          commission: formatAed(candidate.agentCommissionMinor), margin: formatAed(candidate.expectedContributionMinor),
          status: 'DRAFT', canPublish: false,
        })];
      });
    }
    else if(view==='discovery-providers'){
      const imported=new Set(snapshot.discoveryProviderIds??[]);
      const configured=(this.deps.configuredDiscoveryProviders??[]).filter(id=>Object.hasOwn(providerLabels,id));
      rows=[...new Set([...imported,...configured])].map(id=>{
        if(!text(id)||!/^[A-Za-z0-9_.:-]{1,128}$/.test(id))throw new AdministrationError(503);
        return Object.freeze({id,name:Object.hasOwn(providerLabels,id)?providerLabels[id]!:id,hasDiscoveries:imported.has(id),
          ...(id==='FINXPLOR'&&{functions:finxplorFunctions})});
      });
    }
    else if(view==='discoveries')rows=(snapshot.discoveries??[]).filter(r=>!q['provider']||r.providerId===q['provider']).map(r=>{
      const decimal=/^(?:0|[1-9][0-9]{0,23})(?:\.[0-9]{1,18})?$/;
      if(!administrationUuid.test(r.id)||![r.providerId,r.sourceId,r.name,r.brand,r.category,r.delivery].every(text)||
        !/^[A-Z]{3}$/.test(r.sourceCountry)||!/^[A-Z]{3}$/.test(r.currency)||!Number.isFinite(Date.parse(r.observedAt))||
        !['OUTSIDE_PRICED_CATALOGUE_SCOPE','CANONICAL_MAPPING_REQUIRED'].includes(r.reviewReason)||
        !Array.isArray(r.denominations)||r.denominations.length>128||
        ![r.minAmount,r.maxAmount,...r.denominations].every(value=>typeof value==='string'&&decimal.test(value)))throw new AdministrationError(503);
      const market=sourceMarket(r.sourceCountry);
      // Mirrors the frozen local discovery decision for readable staff diagnostics.
      const mappingBlockers=[];
      if(r.sourceCountry!=='ARE')mappingBlockers.push('SERVICE_COUNTRY');
      if(r.currency!=='AED')mappingBlockers.push('CURRENCY');
      if(r.category.toLowerCase()!=='gift card')mappingBlockers.push('PRODUCT_TYPE');
      return Object.freeze({id:r.id,providerId:r.providerId,sourceId:r.sourceId,name:r.name,brand:r.brand,
        sourceCountry:r.sourceCountry,currency:r.currency,category:r.category,delivery:r.delivery,observedAt:r.observedAt,
        sourceCountryName:market.name,sourceCountryCode:SOURCE_GEOGRAPHY[r.sourceCountry]?.[0]??null,
        sourceRegion:market.region,productType:discoveryProductType(r.category),mappingBlockers:Object.freeze(mappingBlockers),
        denominations:Object.freeze([...r.denominations]),minAmount:r.minAmount,maxAmount:r.maxAmount,
        status:r.reviewReason==='OUTSIDE_PRICED_CATALOGUE_SCOPE'?'DISCOVERY_ONLY':'REVIEW_REQUIRED',
        reviewReason:r.reviewReason,pricing:'UNVERIFIED',
        pricingReview:Object.freeze({
          matching:r.reviewReason==='OUTSIDE_PRICED_CATALOGUE_SCOPE'?'OUTSIDE_SCOPE':'NEEDS_CANONICAL_MATCH',
          state:'AWAITING_VERIFIED_TERMS',salePrice:null,
        })});
    });
    else if(view==='imports')rows=snapshot.imports.filter(r=>!q['provider']||r.providerId===q['provider']).map(r=>{
      if(!administrationUuid.test(r.id)||!text(r.providerId)||!['COMPLETE','IN_PROGRESS','FAILED'].includes(r.status)||!Number.isFinite(Date.parse(r.observedAt)))throw new AdministrationError(503);
      return Object.freeze({id:r.id,providerId:r.providerId,status:r.status,observedAt:r.observedAt});});
    else if(view==='publications')rows=(snapshot.publications??[]).filter(r=>!q['product']||r.productId===q['product']).map(r=>{
      if(!administrationUuid.test(r.id)||!products.some(p=>p.id===r.productId)||!/^[1-9][0-9]{0,18}$/.test(r.revision)||
        BigInt(r.revision)>9223372036854775807n||!['ACTIVATE','ROLLBACK'].includes(r.action)||
        !Number.isFinite(Date.parse(r.occurredAt)))throw new AdministrationError(503);
      return Object.freeze({id:r.id,productId:r.productId,revision:r.revision,action:r.action,occurredAt:r.occurredAt});
    });
    else rows=snapshot.drafts.filter(r=>!q['product']||r.productId===q['product']).map(r=>{if(!/^[0-9a-f]{64}$/.test(r.id)||!products.some(p=>p.id===r.productId)||!Number.isSafeInteger(r.version)||r.version<1||!['DRAFT','SUBMITTED','APPROVED','PUBLISHED'].includes(r.status))throw new AdministrationError(503);return Object.freeze({id:r.id,productId:r.productId,version:r.version,status:r.status});});
    const sourceCountries=view==='discoveries' ? Object.freeze([...new Set(rows.map(r=>String(r['sourceCountry'])))].sort()) : undefined;
    const sourceMarkets=sourceCountries?.map(sourceMarket).sort((a,b)=>a.name.localeCompare(b.name,'en'));
    const productTypes=view==='discoveries' ? [...new Set(rows.map(r=>String(r['productType'])))].sort() : undefined;
    const search=q['search']?.normalize('NFKC').toLowerCase().trim();
    const sortKey=(r:typeof rows[number])=>view==='publications'&&q['sort']===undefined
      ? String(9223372036854775807n-BigInt(String(r['revision']))).padStart(19,'0')+r.id : q['sort']==='name'?`${String(r.name??r.id).normalize('NFKC').toLowerCase()}\0${r.id}`:r.id;
    const discoverySearchFields=['name','brand','sourceId','providerId','sourceCountry','currency','category','delivery'];
    rows=rows.filter(r=>{
      if(q['discoveryId'] && r.id!==q['discoveryId'])return false;
      if(q['sourceCountry'] && r['sourceCountry']!==q['sourceCountry'])return false;
      if(q['sourceRegion'] && r['sourceRegion']!==q['sourceRegion'])return false;
      if(q['productType'] && r['productType']!==q['productType'])return false;
      if(!search)return true;
      if(String(r.name??r.id).normalize('NFKC').toLowerCase().includes(search))return true;
      if(view!=='discoveries')return false;
      return discoverySearchFields.some(field=>{
        const value=r[field];
        const term=field==='providerId' && search==='finxplore' ? 'finxplor' : search;
        return typeof value==='string' && value.normalize('NFKC').toLowerCase().includes(term);
      });
    }).slice().sort((a,b)=>sortKey(a)<sortKey(b)?-1:sortKey(a)>sortKey(b)?1:0);
    if(new Set(rows.map(r=>r.id)).size!==rows.length)throw new AdministrationError(503);
    const binding=hash([lease.staffId,tenantId,view,Object.entries(q).filter(([k])=>k!=='cursor').sort()]),cursor=q['cursor']?this.#cursors.get(q['cursor']):undefined;
    let start=0,end=limit;
    if(q['cursor']){
      if(!cursor||cursor.binding!==binding||cursor.revision!==snapshot.revision||now>=cursor.expires)throw new AdministrationError(409);
      const anchor=rows.findIndex(row=>sortKey(row)===cursor.anchor);
      if(anchor<0)throw new AdministrationError(409);
      this.#cursors.delete(q['cursor']);
      if(cursor.direction==='next'){start=anchor+1;end=start+limit;}
      else{end=anchor;start=Math.max(0,end-limit);}
    }
    const items=Object.freeze(rows.slice(start,end));
    if (!await revalidate()) throw new AdministrationError(403);
    await this.deps.audit(lease,view);
    if (!await revalidate()) throw new AdministrationError(403);
    const finalNow=this.deps.now().getTime();
    for(const [key,value] of this.#cursors)if(finalNow>=value.expires)this.#cursors.delete(key);
    const hasPrevious=start>0&&items.length>0,hasNext=end<rows.length&&items.length>0;
    if(this.#cursors.size+Number(hasPrevious)+Number(hasNext)>1000)throw new AdministrationError(503);
    const issueCursor=(row:typeof rows[number],direction:'next'|'previous')=>{
      const id=randomBytes(32).toString('hex');
      this.#cursors.set(id,{binding,revision:snapshot.revision,anchor:sortKey(row),direction,expires:Math.min(finalNow+60000,identity.security.expiresAt*1000)});
      return id;
    };
    return Object.freeze({revision:snapshot.revision,items,count:rows.length,
      ...(view==='discovery-providers'&&{hasConfiguredServices:snapshot.availability.some(row=>row.enabled)}),
      next:hasNext?issueCursor(items.at(-1)!,'next'):null,previous:hasPrevious?issueCursor(items[0]!,'previous'):null,
      ...(sourceCountries && {sourceCountries,sourceMarkets,productTypes})});
  }
}
